import os
import yfinance as yf
import google.generativeai as genai
import feedparser
import datetime
import requests
import time

# --- 設定 Gemini ---
def configure_genai(api_key):
    genai.configure(api_key=api_key)

# --- 抓新聞 ---
def get_financial_news():
    rss_url = "https://news.google.com/rss/topics/CAAqJggBCiCPASowCAqXAg8KCOgDPQkKBAgCGAISBAgBEgISBAgQEgIIABIECAESBAgBEg?hl=en-US&gl=US&ceid=US:en"
    try:
        feed = feedparser.parse(rss_url)
        if not feed.entries:
            return "今日無重大頭條"
        headlines = [f"- {entry.title}" for entry in feed.entries[:8]]
        return "\n".join(headlines)
    except:
        return "新聞抓取失敗"

# --- 抓數據 ---
def get_market_data():
    tickers = ['^VIX', 'SPY', 'RSP', 'QQQ', 'IWM', '^TNX', 'SOXX'] 
    try:
        df = yf.download(tickers, period='1mo', progress=False)['Close']
        if df.empty:
            raise Exception("無法下載數據")
            
        latest = df.iloc[-1]
        prev = df.iloc[-2]
        changes = ((latest - prev) / prev) * 100
        breadth_ratio = latest['RSP'] / latest['SPY']
        
        return {
            'date': datetime.date.today(),
            'vix': latest['^VIX'],
            'tnx': latest['^TNX'],
            'spy': latest['SPY'],
            'spy_chg': changes['SPY'],
            'qqq_chg': changes['QQQ'],
            'iwm_chg': changes['IWM'],
            'soxx_chg': changes['SOXX'],
            'breadth': breadth_ratio,
            'rsp_chg': changes['RSP']
        }
    except Exception as e:
        print(f"數據抓取錯誤: {e}")
        return None

# --- 生成報告 (全自動生存模式) ---
def generate_ai_report(data, news_text):
    
    print("🔍 正在向 Google 查詢所有可用模型...")
    all_models = []
    try:
        # 1. 抓取所有模型
        for m in genai.list_models():
            if 'generateContent' in m.supported_generation_methods:
                all_models.append(m.name)
    except Exception as e:
        return f"❌ 無法連線至 Google API: {e}"

    if not all_models:
        return "❌ 你的 API Key 權限下沒有任何可用的模型。"

    # 2. 智能排序策略
    # 我們希望優先嘗試 'flash' (通常免費且快)，然後才是其他
    # 這樣可以避免一開始就撞到 '2.5-pro' 的付費牆
    def priority_sort(name):
        name = name.lower()
        if 'flash' in name and '1.5' in name: return 0  # 最優先：1.5 Flash
        if 'flash' in name: return 1                    # 次優先：其他 Flash
        if 'pro' in name and '1.5' in name: return 2    # 再次：1.5 Pro
        return 3                                        # 其他 (如 2.5 Pro 或舊版)

    all_models.sort(key=priority_sort)
    print(f"📋 測試順序: {all_models}")

    prompt = f"""
    你是一位華爾街資深投資策略師。請根據以下數據與新聞，用「繁體中文」寫一份深度市場分析日報。

    【今日數據】
    - 日期: {data['date']}
    - VIX: {data['vix']:.2f}
    - 10年債: {data['tnx']:.2f}%
    - SPY 漲跌: {data['spy_chg']:.2f}%
    - QQQ 漲跌: {data['qqq_chg']:.2f}%
    - SOXX 漲跌: {data['soxx_chg']:.2f}%
    - RSP/SPY 廣度: {data['breadth']:.4f}

    【財經新聞】
    {news_text}

    【報告要求】
    1. 標題帶 Emoji。
    2. 分析新聞與殖利率影響。
    3. 判斷紅綠燈號 🟢/🟡/🔴。
    4. 給出 3 點操作建議。
    請直接輸出 Markdown。
    """

    # 3. 大逃殺迴圈：試到成功為止
    last_error = ""
    for model_name in all_models:
        try:
            print(f"🤖 嘗試模型: {model_name} ...")
            model = genai.GenerativeModel(model_name)
            response = model.generate_content(prompt)
            
            # 成功了！
            print(f"✅ 成功！使用模型: {model_name}")
            return f"{response.text}\n\n_(Generated by {model_name})_"
            
        except Exception as e:
            # 失敗了 (可能是 429 Quota, 404 Not Found, 503 Overloaded)
            # 不管是什麼錯，只要不是程式崩潰，就記錄下來並試下一個
            error_msg = str(e)
            print(f"   ⚠️ 失敗 ({error_msg[:50]}...)") 
            last_error = error_msg
            time.sleep(1) # 稍微喘口氣
            continue
            
    # 如果清單裡幾十個模型全掛了
    return f"❌ 所有模型皆嘗試失敗。最後一次錯誤: {last_error}"

# --- 主程式 ---
if __name__ == "__main__":
    TG_TOKEN = os.environ.get('TELEGRAM_TOKEN')
    CHAT_ID = os.environ.get('CHAT_ID')
    API_KEY = os.environ.get('GEMINI_API_KEY')
    
    if TG_TOKEN and CHAT_ID and API_KEY:
        try:
            configure_genai(API_KEY)
            m_data = get_market_data()
            if m_data:
                news = get_financial_news()
                # 這裡會執行上面的大逃殺邏輯
                report = generate_ai_report(m_data, news)
                
                url = f"https://api.telegram.org/bot{TG_TOKEN}/sendMessage"
                payload = {'chat_id': CHAT_ID, 'text': report, 'parse_mode': 'Markdown'}
                requests.post(url, data=payload)
                print("✅ 流程結束")
            else:
                print("⚠️ 數據抓取為空")
        except Exception as e:
            err_msg = f"❌ 執行錯誤: {e}"
            print(err_msg)
            # 嘗試發送錯誤訊息到 Telegram，方便除錯
            try:
                requests.post(f"https://api.telegram.org/bot{TG_TOKEN}/sendMessage", 
                            data={'chat_id': CHAT_ID, 'text': err_msg})
            except:
                pass
    else:
        print("⚠️ 缺少環境變數")
