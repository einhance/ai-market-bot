import os
import yfinance as yf
import google.generativeai as genai
import feedparser
import datetime
import requests
import time

# --- 設定 Gemini ---
def configure_genai(api_key):
    genai.configure(api_key=api_key)

# --- 核心：自動偵測並選出正確的模型名稱 ---
def get_dynamic_model_name():
    print("🔍 正在向 Google 查詢可用模型清單...")
    try:
        # 列出所有支援文字生成的模型
        available_models = []
        for m in genai.list_models():
            if 'generateContent' in m.supported_generation_methods:
                available_models.append(m.name)
        
        print(f"📋 你的 Key 可用清單: {available_models}")
        
        if not available_models:
            return None

        # --- 挑選策略 ---
        # 1. 優先找 Flash (穩定、免費額度高)
        for name in available_models:
            if "flash" in name and "1.5" in name: return name
        
        # 2. 其次找 Pro (性能強)
        for name in available_models:
            if "pro" in name and "1.5" in name: return name
            
        # 3. 再來找舊版 Pro
        for name in available_models:
            if "gemini-pro" in name: return name

        # 4. 真的沒辦法，就回傳清單裡的第一個
        return available_models[0]

    except Exception as e:
        print(f"⚠️ 查詢模型清單失敗: {e}")
        return "models/gemini-pro" # 最後的保底

# --- 抓新聞 ---
def get_financial_news():
    rss_url = "https://news.google.com/rss/topics/CAAqJggBCiCPASowCAqXAg8KCOgDPQkKBAgCGAISBAgBEgISBAgQEgIIABIECAESBAgBEg?hl=en-US&gl=US&ceid=US:en"
    try:
        feed = feedparser.parse(rss_url)
        if not feed.entries:
            return "今日無重大頭條"
        headlines = [f"- {entry.title}" for entry in feed.entries[:8]]
        return "\n".join(headlines)
    except:
        return "新聞抓取失敗"

# --- 抓數據 ---
def get_market_data():
    tickers = ['^VIX', 'SPY', 'RSP', 'QQQ', 'IWM', '^TNX', 'SOXX'] 
    try:
        df = yf.download(tickers, period='1mo', progress=False)['Close']
        if df.empty:
            raise Exception("無法下載數據")
            
        latest = df.iloc[-1]
        prev = df.iloc[-2]
        changes = ((latest - prev) / prev) * 100
        breadth_ratio = latest['RSP'] / latest['SPY']
        
        return {
            'date': datetime.date.today(),
            'vix': latest['^VIX'],
            'tnx': latest['^TNX'],
            'spy': latest['SPY'],
            'spy_chg': changes['SPY'],
            'qqq_chg': changes['QQQ'],
            'iwm_chg': changes['IWM'],
            'soxx_chg': changes['SOXX'],
            'breadth': breadth_ratio,
            'rsp_chg': changes['RSP']
        }
    except Exception as e:
        print(f"數據抓取錯誤: {e}")
        return None

# --- 生成報告 ---
def generate_ai_report(data, news_text):
    
    # 1. 自動取得正確名稱
    target_model_name = get_dynamic_model_name()
    
    if not target_model_name:
        return "❌ 無法找到可用的 Gemini 模型，請檢查 API Key 權限。"

    print(f"🤖 鎖定使用模型: {target_model_name}")
    
    prompt = f"""
    你是一位華爾街資深投資策略師。請根據以下數據與新聞，用「繁體中文」寫一份深度市場分析日報。

    【今日數據】
    - 日期: {data['date']}
    - VIX 恐慌指數: {data['vix']:.2f}
    - 10年期公債殖利率 (TNX): {data['tnx']:.2f}%
    - SPY (標普500) 漲跌: {data['spy_chg']:.2f}%
    - QQQ (那斯達克) 漲跌: {data['qqq_chg']:.2f}%
    - SOXX (半導體) 漲跌: {data['soxx_chg']:.2f}%
    - RSP (等權重) 漲跌: {data['rsp_chg']:.2f}%
    - RSP/SPY 市場廣度: {data['breadth']:.4f}

    【財經新聞頭條】
    {news_text}

    【報告要求】
    1. **標題**: 帶有 Emoji 的吸睛標題。
    2. **市場敘事**: 分析新聞與殖利率如何影響今日股價。
    3. **關鍵指標**: 解讀 VIX 與 市場廣度。
    4. **綜合策略紅綠燈**: 🟢/🟡/🔴 燈號。
    5. **操作建議**: 3 點具體建議。
    請直接輸出 Markdown 格式。
    """

    try:
        model = genai.GenerativeModel(target_model_name)
        response = model.generate_content(prompt)
        # 在報告末尾附上實際使用的模型名稱，方便確認
        return f"{response.text}\n\n_(Generated by {target_model_name})_"
    except Exception as e:
        error_msg = f"⚠️ 模型調用失敗 ({target_model_name}): {str(e)}"
        print(error_msg)
        return error_msg

# --- 主程式 ---
if __name__ == "__main__":
    TG_TOKEN = os.environ.get('TELEGRAM_TOKEN')
    CHAT_ID = os.environ.get('CHAT_ID')
    API_KEY = os.environ.get('GEMINI_API_KEY')
    
    if TG_TOKEN and CHAT_ID and API_KEY:
        try:
            configure_genai(API_KEY)
            m_data = get_market_data()
            
            if m_data:
                news = get_financial_news()
                report = generate_ai_report(m_data, news)
                
                url = f"https://api.telegram.org/bot{TG_TOKEN}/sendMessage"
                payload = {'chat_id': CHAT_ID, 'text': report, 'parse_mode': 'Markdown'}
                requests.post(url, data=payload)
                print("✅ 執行結束")
            else:
                print("⚠️ 數據抓取為空")
        except Exception as e:
            err_msg = f"❌ Bot 執行嚴重錯誤: {e}"
            print(err_msg)
            requests.post(f"https://api.telegram.org/bot{TG_TOKEN}/sendMessage", 
                        data={'chat_id': CHAT_ID, 'text': err_msg})
    else:
        print("⚠️ 缺少環境變數")
